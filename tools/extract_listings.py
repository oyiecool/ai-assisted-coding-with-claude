#!/usr/bin/env python3
"""Extract every code listing from the book manuscript into listings/.

Usage: python tools/extract_listings.py MANUSCRIPT.md [OUTPUT_DIR]

Each fenced code block becomes one file, grouped by chapter and named
after the section it appears in. An index, listings/README.md, maps every
file back to its chapter and section. Re-run it whenever the manuscript
changes; it rewrites the output directory from scratch.
"""
from __future__ import annotations

import re
import shutil
import sys
from pathlib import Path

EXTENSIONS = {
    "python": "py",
    "bash": "sh",
    "json": "json",
    "toml": "toml",
    "make": "mk",
    "yaml": "yml",
    "markdown": "md",
    "text": "txt",
    "csv": "csv",
    "": "txt",
}

CHAPTER_RE = re.compile(r"^## (Chapter (\d+)|Appendix ([A-Z])) — (.+)$")
SECTION_RE = re.compile(r"^#{3,4} (.+)$")


def slug(text: str, limit: int = 48) -> str:
    text = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return text[:limit].rstrip("-") or "listing"


def extract(manuscript: Path, out_dir: Path) -> list[dict]:
    lines = manuscript.read_text(encoding="utf-8").splitlines()
    listings: list[dict] = []
    chapter_key, chapter_title, section = None, None, ""
    in_fence, lang, buf = False, "", []

    for line in lines:
        if line.startswith("```"):
            if not in_fence:
                in_fence, lang, buf = True, line[3:].strip(), []
            else:
                in_fence = False
                if chapter_key:
                    listings.append(
                        {
                            "chapter_key": chapter_key,
                            "chapter_title": chapter_title,
                            "section": section,
                            "lang": lang,
                            "code": "\n".join(buf) + "\n",
                        }
                    )
            continue
        if in_fence:
            buf.append(line)
            continue
        m = CHAPTER_RE.match(line)
        if m:
            if m.group(2):
                chapter_key = f"ch{int(m.group(2)):02d}"
            else:
                chapter_key = f"appendix-{m.group(3).lower()}"
            chapter_title = m.group(1) + " — " + m.group(4)
            section = ""
            continue
        m = SECTION_RE.match(line)
        if m and chapter_key:
            section = m.group(1).strip()

    if out_dir.exists():
        shutil.rmtree(out_dir)
    counters: dict[str, int] = {}
    for item in listings:
        key = item["chapter_key"]
        counters[key] = counters.get(key, 0) + 1
        folder = out_dir / f"{key}-{slug(item['chapter_title'].split(' — ', 1)[1], 40)}"
        folder.mkdir(parents=True, exist_ok=True)
        ext = EXTENSIONS.get(item["lang"], "txt")
        name = f"{counters[key]:02d}-{slug(item['section'] or 'listing')}.{ext}"
        path = folder / name
        path.write_text(item["code"], encoding="utf-8")
        item["path"] = path.relative_to(out_dir).as_posix()

    write_index(out_dir, listings)
    return listings


def write_index(out_dir: Path, listings: list[dict]) -> None:
    rows = [
        "# Code listings",
        "",
        "Every code block printed in *AI-Assisted Coding with Claude*, exactly as it",
        "appears in the book, grouped by chapter. Generated by",
        "`tools/extract_listings.py`; do not edit these files by hand.",
        "",
        "Many listings are prompts or excerpts rather than complete programs. Runnable,",
        "tested versions live in `examples/` and `scenarios/`.",
        "",
    ]
    current = None
    for item in listings:
        if item["chapter_title"] != current:
            current = item["chapter_title"]
            rows += ["", f"## {current}", "", "| File | Section | Language |", "| --- | --- | --- |"]
        section = item["section"] or "(chapter opening)"
        rows.append(f"| [{item['path']}]({item['path']}) | {section} | {item['lang'] or 'text'} |")
    (out_dir / "README.md").write_text("\n".join(rows) + "\n", encoding="utf-8")


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    manuscript = Path(sys.argv[1])
    out_dir = Path(sys.argv[2]) if len(sys.argv) > 2 else Path("listings")
    listings = extract(manuscript, out_dir)
    print(f"Wrote {len(listings)} listings to {out_dir}/")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
